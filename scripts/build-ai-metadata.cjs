// Copy only move metadata; selection scores are implemented in core.js.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const context = { exports: {} };
vm.runInNewContext(fs.readFileSync(path.join(root, 'docs/js/data/nulldex/moves.js'), 'utf8'), context);
// Null's supplied move dex omits target fields. Its other move dex also has
// missing/inaccurate kinds (e.g. Acupressure normal). Use the pinned factual
// upstream target table; retain every Null-specific numerical value and effect.
const targets = require('../tests/fixtures/standard-move-targets.json').targets;
const version = require('./release-config.json');
const rom = require('../tests/fixtures/' + version.romFixture);
const data = {};
for (const move of Object.values(context.exports.BattleMovedex)) {
    const match = (move.shortDesc || '').match(/(\d+)% chance/);
    data[move.name] = { accuracy: move.accuracy === true ? 101 : move.accuracy,
        secondaryChance: match ? Number(match[1]) : null, thawsUser: !!(move.flags && move.flags.defrost),
        basePower: move.basePower, category: move.category, target: move.target, doublesTarget: move.target || targets[move.name],
        doublesTargetSource: move.target ? 'null' : targets[move.name] ? 'standard-fallback' : undefined,
        pp: move.pp, description: move.shortDesc || '', flags: move.flags || {} };
}
// Numeric native fields take precedence over the historical embedded dex.
// A stored secondaryChance is an audited field, not a probability claim for
// every effect script. Use it for effects already identified as secondary.
for (const [name, native] of Object.entries(rom.moves)) {
    const entry = data[name] || { description: '', flags: {}, doublesTarget: targets[name], doublesTargetSource:'standard-fallback' };
    Object.assign(entry, { accuracy:native.accuracy, basePower:native.basePower, category:native.category,
        pp:native.pp, priority:native.priority, numericSource:'rom-'+version.gameVersion, romId:native.id, romOffset:native.offset,
        nativeSecondaryChance:native.secondaryChance, nativeEffect:native.effect, nativeTargetBits:native.targetBits });
    if (entry.secondaryChance !== null && entry.secondaryChance !== undefined) entry.secondaryChance = native.secondaryChance;
    if (native.slicing) entry.flags.slicing=1; else delete entry.flags.slicing;
    if (name === 'Hurricane') entry.flags.wind = 1;
    if (name === 'Powder') entry.flags.powder = 1;
    if (name === 'Glaive Rush') entry.flags.contact = 1;
    data[name] = entry;
}
for (const name of ['Anchor Shot','Spirit Shackle','Alluring Voice']) data[name].secondaryChance=rom.moves[name].secondaryChance;
data['Obstruct'].description = 'Protects from attacks. Contact lowers the attacker\'s Defense by 1.';
data['Obstruct'].effectSource = 'published-move-changes';
Object.assign(data['Tera Starstorm'], { secondaryChance:50, randomStatus:true,
    description:'50% chance to inflict burn, freeze or paralysis.', effectSource:'native-tri-attack-effect-and-published-move-changes' });
// Native selected-target/spread bits are decoded only for independently
// reviewed changes; the existing reviewed target map remains the general base.
for (const name of ['Tera Starstorm','Nihil Light']) {
    const target = name==='Tera Starstorm' ? 'normal' : 'allAdjacentFoes';
    const expected = name==='Tera Starstorm' ? 0 : 8;
    if (rom.moves[name].targetBits!==expected) throw Error('Native target anchor changed: '+name);
    data[name].doublesTarget=target; data[name].doublesTargetSource='rom-'+version.gameVersion;
}
fs.writeFileSync(path.join(root, 'docs/js/null_ai/metadata.js'),
    '// Generated by scripts/build-ai-metadata.cjs: ROM numeric values, reviewed documentation, historical descriptive fallback.\n' +
    'var NullAIMoveMetadata = ' + JSON.stringify(data, null, 2) + ';\n');
