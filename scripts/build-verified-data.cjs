'use strict';
// Build an additive data layer from the pinned ROM extraction. Never rewrite
// the supplied trainers, calculator tables, or the old embedded Pokédex.
const fs=require('node:fs'),path=require('node:path'),calc=require('../docs/calc');
const root=path.resolve(__dirname,'..'),version=require('./release-config.json'),rom=require('../tests/fixtures/'+version.romFixture);
const id=calc.toID;
const canonical=v=>Array.isArray(v)?v.map(canonical):v&&typeof v==='object'?Object.fromEntries(Object.keys(v).sort().map(k=>[k,canonical(v[k])])):v;
const equal=(a,b)=>JSON.stringify(canonical(a))===JSON.stringify(canonical(b));
const nativeSpecies=Object.fromEntries(Object.entries(rom.species).map(([name,row])=>[id(name),row]));
const nativeMoves=Object.fromEntries(Object.entries(rom.moves).map(([name,row])=>[id(name),row]));
const abilityNames=Object.fromEntries(calc.ABILITIES[9].map(name=>[id(name),name]));
// Battle identities whose Lua label differs from the calculator's identity.
// Minior's unqualified Lua entry is the meteor shell; its core is slot 1321.
const aliases={
 'Minior': 'Minior [ROM 1321]', 'Minior-Meteor':'Minior',
 'Zygarde-10%':'Zygarde-10', 'Zygarde-Complete':'Zygarde-Complete',
 'Zygarde-Mega':'Zygarde-Complete-Mega',
 'Poltchageist-Artisan':'Poltchageist',
 'Darmanitan-Zen-Mode':'Darmanitan-Zen',
 'Aegislash-Shield':'Aegislash-Both', 'Sinistcha-Masterpiece':'Sinistcha',
 'Vivillon-Fancy':'Vivillon', 'Vivillon-Pokeball':'Vivillon',
};
const species={},moves={},unmatchedSpecies=[],unmatchedMoves=[],differences=[];
for(const [name,old]of Object.entries(calc.SPECIES[9])){
 // The inherited "Both" entry is a virtual damage convenience, combining
 // offensive Blade and defensive Shield stats. It is not a native form.
 if(name==='Aegislash-Both'){unmatchedSpecies.push(name);continue;}
 const row=nativeSpecies[id(aliases[name]||name)];
 if(!row){unmatchedSpecies.push(name);continue;}
 const abilities=Object.fromEntries(Object.entries(row.abilities).map(([slot,name])=>[slot,abilityNames[id(name)]||name]));
 const patch={baseStats:row.baseStats,types:row.types,abilities,romId:row.id,romOffset:row.offset,
  catchRate:row.catchRate,wildHeldItems:row.wildHeldItems};
 if(row.weightkg>0&&row.id<=1025&&!aliases[name])patch.weightkg=row.weightkg;
 species[name]=patch;
 const before={baseStats:{hp:old.bs.hp,atk:old.bs.at,def:old.bs.df,spa:old.bs.sa,spd:old.bs.sd,spe:old.bs.sp},types:old.types,defaultAbility:old.abilities&&old.abilities[0],weightkg:old.weightkg};
 const after={baseStats:row.baseStats,types:row.types,defaultAbility:abilities[0],weightkg:patch.weightkg??old.weightkg};
 const fields=Object.keys(before).filter(k=>!equal(before[k],after[k]));
 if(fields.length)differences.push({kind:'species',name,romId:row.id,fields,before,after});
}
for(const [name,old]of Object.entries(calc.MOVES[9])){
 const row=nativeMoves[id(name)];
 if(!row){unmatchedMoves.push(name);continue;}
 // Values of 1 denote formula-driven power in the native table. Keep the
 // calculator's formula sentinel while retaining the native value in metadata.
 const patch={bp:row.basePower===1?old.bp:row.basePower,type:row.type,category:row.category,
  priority:row.priority,pp:row.pp,isSlicing:row.slicing,romId:row.id,romOffset:row.offset};
 // Native Sheer Force uses byte16 bit1, independently of effect chance.
 // Anchor Shot / Spirit Shackle / Alluring Voice retain that eligibility.
 patch.secondaries=!!(Buffer.from(row.bytes,'hex')[16]&2);
 if(name==='Hurricane')patch.isWind=true;
 if(name==='Glaive Rush')patch.makesContact=true;
 if(name==='Powder')patch.isPowder=true;
 // Tera Starstorm shares the native Tri Attack effect (36), including the
 // secondary status chance. This is independently read from both records.
 if(name==='Tera Starstorm'){if(row.effect!==rom.moves['Tri Attack'].effect||row.secondaryChance!==50)throw Error('Starstorm effect anchor changed');patch.secondaries=true;}
 if(name==='Tera Starstorm'||name==='Nihil Light')patch.target=name==='Tera Starstorm'?'normal':'allAdjacentFoes';
 moves[name]=patch;
 const current=new calc.Move(9,name),before={bp:current.bp,type:current.type,category:current.category,priority:current.priority,slicing:!!current.flags.slicing};
 const after={bp:patch.bp===old.bp?current.bp:patch.bp,type:patch.type,category:patch.category,priority:patch.priority,slicing:patch.isSlicing};
 const fields=Object.keys(before).filter(k=>before[k]!==after[k]);
 if(fields.length)differences.push({kind:'move',name,romId:row.id,fields,before,after});
}
const data={schemaVersion:1,gameVersion:version.gameVersion,romSHA256:rom.romSHA256,authority:'Supplied ROM '+version.gameVersion+', then published documentation; no live Pokédex imports.',species,moves};
fs.writeFileSync(path.join(root,'docs/js/null_ai/verified-data.js'),'// Generated by scripts/build-verified-data.cjs from the pinned ROM audit.\nvar NullVerifiedData = '+JSON.stringify(data,null,2)+';\nif (typeof module === "object" && module.exports) module.exports = NullVerifiedData;\n');
const report={romSHA256:rom.romSHA256,speciesMatched:Object.keys(species).length,movesMatched:Object.keys(moves).length,aliases,unmatchedSpecies,unmatchedMoves,differences,
 limitations:['Form weights outside national slots 1-1025 have not been decoded. Existing values are retained.','Selected native AI helpers and changed branches have been disassembled and pinned; full native/RNG parity is not certified.','Slicing, powder, wind and Sheer Force bits are ROM-derived; other inherited flags remain unless separately verified.']};
fs.writeFileSync(path.join(root,'verification/rom-data-comparison.json'),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify({species:report.speciesMatched,moves:report.movesMatched,differences: differences.length,unmatchedSpecies:unmatchedSpecies.length}));
